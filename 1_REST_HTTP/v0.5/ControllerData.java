public class ControllerData {
    private int robotsActive = 0;
    private String captain = null;
    private String health = null;

    // getters/setters
    public int getRobotsActive() { return robotsActive; }
    public void setRobotsActive(int robotsActive) { this.robotsActive = robotsActive; }
    public String getCaptain() { return captain; }
    public void setCaptain(String captain) { this.captain = captain; }
    public String getHealth() { return health; }
    public void setHealth(String health) { this.health = health; }
}
